#!/usr/bin/env python3
"""Generate the multi-machine part of README.md (second machine and cross-machine comparison) from the datasets.

  python benchmark/machines_table.py                  # print the block
  python benchmark/machines_table.py --update-readme  # rewrite the block between the markers in README.md
  python benchmark/machines_table.py --check          # exit 1 if README.md differs from the data (used by the tests)

Datasets: the laptop folder benchmark/results/ (one session) and the second machine's folder
benchmark/results_pc_i5-13500_wsl2/ (one sub-folder per measurement session, each with raw_runs.csv, benchmark_results.csv
and hardware_environment.json). The script refuses to produce any statement unless every run is `ok`, the number of runs of each
session equals what its recorded protocol implies, sessions of one machine do not share a (workload, size), and the sessions
come from the same CPU. No result number in the README block is typed by hand.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
START = "<!-- machines:start (generated by benchmark/machines_table.py; do not edit by hand) -->"
END = "<!-- machines:end -->"
MODELS = ["omp", "thread2", "mpi"]
NAMES = {"seq": "Sequential", "omp": "OpenMP", "thread2": "Pthreads", "mpi": "MPI"}
WORKLOADS = {"matrix": "Matrix multiplication", "mergesort": "Merge sort"}
MIN_REPS_FOR_INTERVAL = 5


def size_label(workload: str, size: int) -> str:
    return f"{size}×{size}" if workload == "matrix" else f"{size:,}"


def _order(df: pd.DataFrame) -> pd.DataFrame:
    return (df.assign(_w=df["workload"].map({"matrix": 0, "mergesort": 1}).fillna(2),
                      _m=df["model"].map({"seq": 0, "omp": 1, "thread2": 2, "mpi": 3}))
              .sort_values(["_w", "size", "_m", "workers"]).drop(columns=["_w", "_m"]))


def _rng(series, fmt="{:.2f}") -> str:
    lo, hi = fmt.format(series.min()), fmt.format(series.max())
    return lo if lo == hi else f"{lo}–{hi}"


def expected_runs(df: pd.DataFrame, protocol: dict) -> int:
    total = 0
    for wl, g in df.groupby("workload"):
        reps = protocol.get("sort_reps", protocol["reps"]) if wl == "mergesort" else protocol["reps"]
        total += len(g) * reps
    return total


def load_machine(root) -> tuple:
    """Return (configurations, raw runs, hardware records) of one machine; every session is validated."""
    root = Path(root)
    if (root / "benchmark_results.csv").exists():
        dirs = [root]
    else:
        dirs = sorted(d for d in root.iterdir() if d.is_dir() and (d / "benchmark_results.csv").exists()) if root.is_dir() else []
    if not dirs:
        sys.exit(f"ERROR: no result folder found in {root}")
    cfgs, raws, hws, seen = [], [], [], set()
    for d in dirs:
        for f in ("raw_runs.csv", "hardware_environment.json"):
            if not (d / f).exists():
                sys.exit(f"ERROR: {d} has no {f}")
        cfg = pd.read_csv(d / "benchmark_results.csv")
        raw = pd.read_csv(d / "raw_runs.csv")
        hw = json.loads((d / "hardware_environment.json").read_text())
        bad = raw[raw["status"] != "ok"]
        if len(bad):
            sys.exit(f"ERROR: {d.name}: {len(bad)} of {len(raw)} runs are not 'ok'; resolve them before publishing 'all runs validated'.")
        exp = expected_runs(cfg, hw["protocol"])
        if len(raw) != exp:
            sys.exit(f"ERROR: {d.name}: raw_runs.csv has {len(raw)} runs but the protocol implies {exp}: a repetition is missing.")
        keys = set(zip(cfg["workload"], cfg["size"]))
        if keys & seen:
            sys.exit(f"ERROR: {d.name}: sessions of one machine share (workload, size) {sorted(keys & seen)}")
        seen |= keys
        cfgs.append(cfg.assign(session=d.name))
        raws.append(raw.assign(session=d.name))
        hws.append(hw)
    if len({h["cpu_model"] for h in hws}) != 1:
        sys.exit("ERROR: the sessions of one machine report different CPU models")
    return pd.concat(cfgs, ignore_index=True), pd.concat(raws, ignore_index=True), hws


def scaling_table(df: pd.DataFrame) -> str:
    ws = sorted(int(w) for w in df["workers"].unique() if w > 1)
    over = set(df[df["oversubscribed"]]["workers"])
    head = " | ".join(f"{w} workers{'*' if w in over else ''}" for w in ws)
    lines = [f"| Workload | Size | Model | {head} |", "|---|---|---|" + "---|" * len(ws)]
    d = _order(df[df["model"] != "seq"])
    for (wl, size, model), g in d.groupby(["workload", "size", "model"], sort=False):
        s = g.set_index("workers")["kernel_speedup_vs_1worker"]
        cells = [f"{s[w]:.2f} ({s[w] / w:.2f})" if w in s.index and pd.notna(s[w]) else "–" for w in ws]
        lines.append(f"| {WORKLOADS.get(wl, wl)} | {size_label(wl, int(size))} | {NAMES[model]} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def _best(g: pd.DataFrame):
    return g.loc[g["kernel_median_s"].idxmin()]


def _cfg_label(r) -> str:
    return f"{NAMES[r.model]}, {int(r.workers)} worker{'s' if r.workers > 1 else ''}{'*' if r.oversubscribed else ''}"


def shared_pairs(a: pd.DataFrame, b: pd.DataFrame) -> list:
    keys = set(zip(a["workload"], a["size"])) & set(zip(b["workload"], b["size"]))
    return sorted(keys, key=lambda k: (0 if k[0] == "matrix" else 1, k[1]))


def compare_table(lap: pd.DataFrame, pc: pd.DataFrame) -> str:
    lines = ["| Workload | Size | Sequential kernel, laptop (s) | Sequential kernel, desktop (s) | desktop / laptop | "
             "Fastest configuration, laptop (kernel s) | Fastest configuration, desktop (kernel s) | Laptop time / desktop time |",
             "|---|---|---|---|---|---|---|---|"]
    for wl, size in shared_pairs(lap, pc):
        gl = lap[(lap["workload"] == wl) & (lap["size"] == size)]
        gp = pc[(pc["workload"] == wl) & (pc["size"] == size)]
        sl = float(gl[gl["model"] == "seq"]["kernel_median_s"].iloc[0])
        sp = float(gp[gp["model"] == "seq"]["kernel_median_s"].iloc[0])
        bl, bp = _best(gl), _best(gp)
        lines.append(f"| {WORKLOADS.get(wl, wl)} | {size_label(wl, int(size))} | {sl:#.3g} | {sp:#.3g} | {sp / sl:.2f} | "
                     f"{_cfg_label(bl)} ({bl.kernel_median_s:#.3g}) | {_cfg_label(bp)} ({bp.kernel_median_s:#.3g}) | "
                     f"{bl.kernel_median_s / bp.kernel_median_s:.1f}× |")
    return "\n".join(lines)


def key_numbers(lap: pd.DataFrame, pc: pd.DataFrame) -> list:
    valid = pc[pc["scaling_valid"] & (pc["model"] != "seq")]
    wv, wmax = int(valid["workers"].max()), int(pc["workers"].max())
    out = []
    for wl in ("matrix", "mergesort"):
        top = valid[(valid["workload"] == wl) & (valid["workers"] == wv)]
        if top.empty:
            continue
        thr = top[top["model"].isin(["omp", "thread2"])]["kernel_speedup_vs_1worker"]
        mp = top[top["model"] == "mpi"]["kernel_speedup_vs_1worker"]
        out.append(f"{WORKLOADS[wl]}, {wv} workers (the largest count the harness treats as valid scaling): kernel speedup over the same "
                   f"model with 1 worker is {_rng(thr)} for OpenMP and Pthreads and {_rng(mp)} for MPI.")
    kt = pc.pivot_table(index=["workload", "size", "model"], columns="workers", values="kernel_median_s")
    if wmax in kt.columns and wv in kt.columns and wmax != wv:
        parts = []
        for m in MODELS:
            rows = [i for i in kt.index if i[2] == m]
            slower = sum(1 for i in rows if kt.loc[i, wmax] > kt.loc[i, wv])
            parts.append(f"{NAMES[m]} in {slower} of {len(rows)}")
        out.append(f"With {wmax} workers (flagged `oversubscribed`, not a scaling claim) the kernel was slower than with {wv} workers "
                   f"in these (workload, size) cases: " + "; ".join(parts) + ".")
    pairs = shared_pairs(lap, pc)
    if pairs:
        ratios = []
        for wl, size in pairs:
            sl = lap[(lap["workload"] == wl) & (lap["size"] == size) & (lap["model"] == "seq")]["kernel_median_s"].iloc[0]
            sp = pc[(pc["workload"] == wl) & (pc["size"] == size) & (pc["model"] == "seq")]["kernel_median_s"].iloc[0]
            ratios.append(sp / sl)
        r = pd.Series(ratios)
        where = "shared size" if len(pairs) == 1 else f"{len(pairs)} shared sizes"
        out.append(f"Sequential kernel time of the desktop relative to the laptop at the {where}: {_rng(r)} "
                   f"(1.00 = equal, above 1 = the desktop was slower). The cause was not identified (see the dataset card).")
    few = pc.groupby(["workload", "size"])["n_runs"].min()
    few = few[few < MIN_REPS_FOR_INTERVAL]
    if len(few):
        names = ", ".join(f"{WORKLOADS.get(wl, wl).lower()} {size_label(wl, int(s))} ({int(n)} repetitions)" for (wl, s), n in few.items())
        out.append(f"Sizes measured with fewer than {MIN_REPS_FOR_INTERVAL} repetitions have no speedup interval and noisier medians: {names}.")
    return out


def render_block(laptop_dir, pc_dir) -> str:
    lap, _, _ = load_machine(laptop_dir)
    pc, praw, phw = load_machine(pc_dir)
    cores = int(phw[0]["effective_cores"])
    sessions = pc["session"].nunique()
    parts = [START, "",
             f"All {len(praw)} recorded runs of this machine exited cleanly and printed exactly the sequential program's output "
             f"({len(pc)} configurations in {sessions} sessions; interrupted attempts are not part of the dataset).", "",
             "**Kernel speedup over the same model with 1 worker (efficiency in brackets).** Medians of the repetitions; "
             f"`*` = more workers than the {cores} cores the harness counted, flagged `oversubscribed` in the dataset and not a "
             "scaling claim.", "", scaling_table(pc), "",
             "**Laptop and desktop at the sizes both machines measured.** Kernel time (s), median of the repetitions; the fastest "
             "configuration is the one with the lowest median over all models and worker counts (`*` = oversubscribed per the harness).",
             "", compare_table(lap, pc), "",
             "**Key numbers**", ""] + [f"- {s}" for s in key_numbers(lap, pc)] + ["", END]
    return "\n".join(parts)


def replace_block(readme: str, block: str) -> str:
    if START not in readme or END not in readme:
        sys.exit("ERROR: the machines markers are missing from README.md")
    a = readme.index(START)
    b = readme.index(END) + len(END)
    return readme[:a] + block + readme[b:]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--laptop-dir", default=str(HERE / "results"))
    ap.add_argument("--pc-dir", default=str(HERE / "results_pc_i5-13500_wsl2"))
    ap.add_argument("--readme", default=str(ROOT / "README.md"))
    ap.add_argument("--update-readme", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    block = render_block(a.laptop_dir, a.pc_dir)
    if a.update_readme or a.check:
        text = Path(a.readme).read_text(encoding="utf-8")
        new = replace_block(text, block)
        if a.check:
            if new != text:
                print("README.md machines block differs from the data; run: python3 benchmark/machines_table.py --update-readme")
                return 1
            print("README.md machines block matches the data")
            return 0
        Path(a.readme).write_text(new, encoding="utf-8")
        print(f"updated {a.readme}")
        return 0
    print(block)
    return 0


if __name__ == "__main__":
    sys.exit(main())
