#!/usr/bin/env python3
"""Generate the Results block of README.md from the dataset, so that no result number is typed by hand.

  python benchmark/results_table.py                 # print the block
  python benchmark/results_table.py --update-readme # rewrite the block between the markers in README.md
  python benchmark/results_table.py --check         # exit 1 if README.md differs from the data (used by the tests)

Inputs (default folder benchmark/results/): benchmark_results.csv, raw_runs.csv and hardware_environment.json.
The script refuses to produce the sentence "all runs validated" unless every recorded run is `ok` AND the number of runs
equals what the recorded protocol implies (so a missing repetition is detected).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
START = "<!-- results:start (generated by benchmark/results_table.py; do not edit by hand) -->"
END = "<!-- results:end -->"
MODEL_ORDER = ["omp", "thread2", "mpi"]
NAMES = {"seq": "Sequential", "omp": "OpenMP", "thread2": "Pthreads", "mpi": "MPI"}
WORKLOADS = {"matrix": "Matrix multiplication", "mergesort": "Merge sort"}
NOISY_CV = 0.25     # a single slow repetition dominates the CV above this value


def size_label(workload: str, size: int) -> str:
    return f"{size}×{size}" if workload == "matrix" else f"{size:,}"


def _order(df: pd.DataFrame) -> pd.DataFrame:
    return (df.assign(_w=df["workload"].map({"matrix": 0, "mergesort": 1}).fillna(2),
                      _m=df["model"].map({"seq": 0, "omp": 1, "thread2": 2, "mpi": 3}))
              .sort_values(["_w", "size", "_m", "workers"]).drop(columns=["_w", "_m"]))


def top_workers(df: pd.DataFrame) -> int:
    return int(df[df["scaling_valid"] & (df["model"] != "seq")]["workers"].max())


def _with_interval(r) -> str:
    lo = getattr(r, "kernel_speedup_vs_1worker_lo", float("nan"))
    hi = getattr(r, "kernel_speedup_vs_1worker_hi", float("nan"))
    value = f"{r.kernel_speedup_vs_1worker:.2f}"
    return value if pd.isna(lo) or pd.isna(hi) else f"{value} ({lo:.2f}–{hi:.2f})"


def scaling_table(df: pd.DataFrame) -> str:
    w = top_workers(df)
    d = _order(df[df["scaling_valid"] & (df["model"] != "seq") & (df["workers"] == w)])
    lines = [f"| Workload | Size | Model | Kernel speedup vs 1 worker ({w} workers; conservative interval) | Efficiency | "
             f"Kernel speedup vs sequential | Wall speedup vs 1 worker |", "|---|---|---|---|---|---|---|"]
    for r in d.itertuples():
        lines.append(f"| {WORKLOADS.get(r.workload, r.workload)} | {size_label(r.workload, r.size)} | {NAMES[r.model]} | "
                     f"{_with_interval(r)} | {r.kernel_speedup_vs_1worker / w:.2f} | "
                     f"{r.kernel_speedup_vs_seq:.2f} | {r.speedup_vs_1worker:.2f} |")
    return "\n".join(lines)


def sweep_table(df: pd.DataFrame) -> str:
    wmax = int(df["workers"].max())
    over = sorted(df[df["oversubscribed"]]["workers"].unique())
    header = " | ".join(f"{w} worker{'s' if w > 1 else ''}{'*' if w in over else ''}" for w in range(1, wmax + 1))
    lines = [f"| Workload | Size | Model | {header} |", "|---|---|---|" + "---|" * wmax]
    for (wl, size), g in _order(df).groupby(["workload", "size"], sort=False):
        for model in ["seq"] + MODEL_ORDER:
            m = g[g["model"] == model].set_index("workers")["kernel_median_s"]
            if m.empty:
                continue
            cells = [f"{m[w]:#.3g}" if w in m.index and pd.notna(m[w]) else "–" for w in range(1, wmax + 1)]
            lines.append(f"| {WORKLOADS.get(wl, wl)} | {size_label(wl, size)} | {NAMES[model]} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def _rng(series, fmt="{:.2f}") -> str:
    return f"{fmt.format(series.min())}–{fmt.format(series.max())}"


def key_numbers(df: pd.DataFrame) -> list:
    w = top_workers(df)
    wmax = int(df["workers"].max())
    valid = df[df["scaling_valid"]]
    par = valid[valid["model"] != "seq"]
    top = par[par["workers"] == w]
    out = []
    ks = top["kernel_speedup_vs_1worker"]
    out.append(f"Kernel speedup with {w} workers over the same model with 1 worker: {_rng(ks)}; "
               + (f"no configuration reaches the ideal {w}×." if ks.max() < w else f"the ideal {w}× is reached or exceeded."))
    if "kernel_speedup_vs_1worker_hi" in top and top["kernel_speedup_vs_1worker_hi"].notna().any():
        t = top.dropna(subset=["kernel_speedup_vs_1worker_lo", "kernel_speedup_vs_1worker_hi"])
        below = int((t["kernel_speedup_vs_1worker_hi"] < w).sum())
        above1 = int((t["kernel_speedup_vs_1worker_lo"] > 1).sum())
        out.append(f"The conservative interval of the kernel speedup (order statistics of the repetitions; at least 87% coverage "
                   f"with 5 repetitions per side, 93% with 15) lies entirely above 1 in {above1} of {len(t)} configurations and "
                   f"entirely below the ideal {w}× in {below} of {len(t)}.")
    one = par[(par["workers"] == 1) & par["model"].isin(["omp", "thread2"])]["kernel_speedup_vs_seq"]
    out.append(f"A one-worker OpenMP or Pthreads run takes {_rng(one)} times the speed of the sequential program "
               f"(kernel time, the same algorithm), which checks that the sequential baseline is not biased.")
    mm = par[(par["workload"] == "matrix") & (par["model"] == "mpi") & (par["workers"] == 1)].sort_values("size")
    if not mm.empty:
        sizes = ", ".join(f"{size_label('matrix', int(s))}: {v:.2f}" for s, v in zip(mm["size"], mm["kernel_speedup_vs_seq"]))
        out.append(f"The one-rank MPI matrix code is not equal in speed to the sequential program ({sizes}; 1.00 = equal); it is a "
                   f"different implementation (flat arrays), so scaling is judged against each model's own one-worker run, "
                   f"and 'speedup vs sequential' mixes implementation and parallelism.")
    for wl in sorted(top["workload"].unique()):
        t = top[top["workload"] == wl]["speedup_vs_1worker"]
        out.append(f"{WORKLOADS.get(wl, wl)}: end-to-end (wall-time) speedup with {w} workers is only {_rng(t)} because "
                   f"reading and printing the text files is serial.")
    mw = top[top["model"] == "mpi"]["speedup_vs_seq"]
    if not mw.empty:
        out.append(f"MPI wall time relative to the sequential program ({w} ranks): {_rng(mw)} of its speed, because of "
                   f"`mpirun` start-up and output forwarding.")
    ov = df[df["oversubscribed"]]
    if not ov.empty:
        kt = df.pivot_table(index=["workload", "size", "model"], columns="workers", values="kernel_median_s")
        for wl in sorted(par["workload"].unique()):
            sizes = sorted(par[par["workload"] == wl]["size"].unique())
            sel = sizes[-2:] if wl == "matrix" else sizes[-1:]
            rows = [(wl, s, m) for s in sel for m in MODEL_ORDER if (wl, s, m) in kt.index]
            ratio = pd.Series([kt.loc[r, wmax] / kt.loc[r, w] for r in rows if wmax in kt.columns]).dropna()
            if ratio.empty:
                continue
            what = ("the two largest matrix sizes" if wl == "matrix" else "the largest sort size")
            out.append(f"Beyond the physical cores (flagged, not a scaling claim), {WORKLOADS.get(wl, wl).lower()} with "
                       f"{wmax} workers took {_rng(ratio)} times as long as with {w} workers ({what}, all three models).")
    low = ((valid["kernel_median_s"] - valid["kernel_min_s"]) / valid["kernel_median_s"])
    high = ((valid["kernel_max_s"] - valid["kernel_median_s"]) / valid["kernel_median_s"])
    out.append(f"Run-to-run noise is right-skewed: across the {len(valid)} valid configurations the best repetition is "
               f"typically {low.median() * 100:.0f}% below the median, the slowest {high.median() * 100:.0f}% above it "
               f"(medians are reported; every repetition is visible in the kernel-time figures).")
    noisy = _order(valid[valid["kernel_cv"] > NOISY_CV])
    if not noisy.empty:
        names = "; ".join(f"{WORKLOADS.get(r.workload, r.workload).lower()} {size_label(r.workload, r.size)} "
                          f"{NAMES[r.model]} with {r.workers} worker{'s' if r.workers > 1 else ''} (CV {r.kernel_cv:.2f})"
                          for r in noisy.itertuples())
        out.append(f"Configurations with kernel CV above {NOISY_CV}, where one slow repetition dominates: {names}.")
    return out


def expected_runs(df: pd.DataFrame, protocol: dict) -> int:
    total = 0
    for wl, g in df.groupby("workload"):
        reps = protocol.get("sort_reps", protocol["reps"]) if wl == "mergesort" else protocol["reps"]
        total += len(g) * reps
    return total


def runs_sentence(df: pd.DataFrame, raw: pd.DataFrame, hw: dict) -> str:
    bad = raw[raw["status"] != "ok"]
    if len(bad):
        sys.exit(f"ERROR: {len(bad)} of {len(raw)} runs are not 'ok'; resolve them before publishing 'all runs validated'.")
    exp = expected_runs(df, hw["protocol"])
    if len(raw) != exp:
        sys.exit(f"ERROR: raw_runs.csv has {len(raw)} runs but the protocol implies {exp}: a repetition is missing.")
    return (f"All {len(raw)} recorded runs exited cleanly and printed exactly the sequential program's output "
            f"({len(df)} configurations).")


def render_block(results: Path) -> str:
    df = pd.read_csv(results / "benchmark_results.csv")
    raw = pd.read_csv(results / "raw_runs.csv") if (results / "raw_runs.csv").exists() else None
    hw = json.loads((results / "hardware_environment.json").read_text()) \
        if (results / "hardware_environment.json").exists() else None
    parts = [START, ""]
    if raw is not None and hw is not None:
        parts += [runs_sentence(df, raw, hw), ""]
    w = top_workers(df)
    parts += [f"**Scaling from 1 to {w} workers.** Each model against its own one-worker run; efficiency = kernel speedup / {w}; "
              f"'vs sequential' compares with the sequential program. Medians of the repetitions.", "", scaling_table(df), "",
              "**Key numbers**", ""] + [f"- {s}" for s in key_numbers(df)]
    parts += ["", f"**Kernel time (median seconds) for every worker count.** Columns marked * exceed the "
                  f"{w} physical cores: they are in the dataset but flagged `oversubscribed` and are not scaling claims.", "",
              sweep_table(df), "", END]
    return "\n".join(parts)


def replace_block(readme: str, block: str) -> str:
    if START not in readme or END not in readme:
        sys.exit("ERROR: the results markers are missing from README.md")
    a = readme.index(START)
    b = readme.index(END) + len(END)
    return readme[:a] + block + readme[b:]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--results-dir", default=str(HERE / "results"))
    ap.add_argument("--readme", default=str(ROOT / "README.md"))
    ap.add_argument("--update-readme", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    block = render_block(Path(a.results_dir))
    readme_path = Path(a.readme)
    if a.update_readme or a.check:
        text = readme_path.read_text(encoding="utf-8")
        new = replace_block(text, block)
        if a.check:
            if new != text:
                print("README.md results block differs from the data; run: python3 benchmark/results_table.py --update-readme")
                return 1
            print("README.md results block matches the data")
            return 0
        readme_path.write_text(new, encoding="utf-8")
        print(f"updated {readme_path}")
        return 0
    print(block)
    return 0


if __name__ == "__main__":
    sys.exit(main())
